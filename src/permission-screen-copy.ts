type ScreenRecordingCopy = {
  screenTitle: string;
  screenDescription: string;
  screenAddedTitle: string;
  screenAddedBody: string;
  screenDragInstruction: string;
  screenDragInstructionRuns: string;
  screenChecking: string;
  done: string;
  screenUnknown: string;
};

type LocalizedScreenCopy = Omit<ScreenRecordingCopy, "screenDragInstruction" | "screenDragInstructionRuns"> & {
  dragPrefix: string;
  dragSuffix: string;
};

type InstructionRun = { text: string; role: "primary" | "secondary" };

const CHATGPT_APP_PATH = "/Applications/ChatGPT.app";

function makeScreenCopy(copy: LocalizedScreenCopy): ScreenRecordingCopy {
  const screenDragInstruction = `${copy.dragPrefix}${CHATGPT_APP_PATH}${copy.dragSuffix}`;
  const runs: InstructionRun[] = [
    { text: copy.dragPrefix, role: "secondary" },
    { text: CHATGPT_APP_PATH, role: "primary" },
    { text: copy.dragSuffix, role: "secondary" },
  ];
  return {
    screenTitle: copy.screenTitle,
    screenDescription: copy.screenDescription,
    screenAddedTitle: copy.screenAddedTitle,
    screenAddedBody: copy.screenAddedBody,
    screenDragInstruction,
    screenDragInstructionRuns: JSON.stringify(runs.filter(run => run.text.length > 0)),
    screenChecking: copy.screenChecking,
    done: copy.done,
    screenUnknown: copy.screenUnknown,
  };
}

